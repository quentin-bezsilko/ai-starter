package com.qbe.aistarter.controller;

import com.qbe.aistarter.dto.LlmResponseDto;
import com.qbe.aistarter.dto.PromptDto;
import com.qbe.aistarter.service.AssistantService;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.media.Content;
import io.swagger.v3.oas.annotations.media.Schema;
import io.swagger.v3.oas.annotations.responses.ApiResponse;
import io.swagger.v3.oas.annotations.responses.ApiResponses;
import io.swagger.v3.oas.annotations.tags.Tag;
import jakarta.validation.Valid;
import jakarta.validation.constraints.NotNull;
import java.util.Objects;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.http.MediaType;
import org.springframework.http.ResponseEntity;
import org.springframework.validation.annotation.Validated;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RestController;

@Slf4j
@Validated
@RestController
@RequiredArgsConstructor
@RequestMapping(value = "/api/v1/assistant", produces = MediaType.APPLICATION_JSON_VALUE)
@Tag(name = "Assistant", description = "Endpoints de question-réponse auprès de l'assistant IA")
public class AssistantController {

    private final AssistantService assistantService;

    /**
     * Ask the assistant a question with a structured prompt template
     * and a configurable response level.
     *
     * @param request payload containing the conversation ID, the question, and the response level
     * @return response generated by the LLM along with any sources
     */
    @PostMapping(value = "/question", consumes = MediaType.APPLICATION_JSON_VALUE)
    @Operation(
            summary = "Ask a question with a prompt template",
            description = "Executes a request enriched by a prompt template and a response level.")
    @ApiResponses({
        @ApiResponse(
                responseCode = "200",
                description = "Response generated successfully",
                content =
                        @Content(
                                mediaType = MediaType.APPLICATION_JSON_VALUE,
                                schema = @Schema(implementation = LlmResponseDto.class))),
        @ApiResponse(responseCode = "400", description = "Invalid request or missing parameters", content = @Content),
        @ApiResponse(
                responseCode = "500",
                description = "Internal error while calling the AI service",
                content = @Content)
    })
    public ResponseEntity<LlmResponseDto> askWithPromptTemplate(@Valid @NotNull @RequestBody PromptDto request) {
        PromptDto safeRequest = Objects.requireNonNull(request, "request must not be null");
        log.debug(
                "Processing a question with template (conversationId={}, responseLevel={})",
                safeRequest.conversationId(),
                safeRequest.responseLevel());

        LlmResponseDto response = assistantService.askWithPromptTemplate(
                safeRequest.conversationId(), safeRequest.question(), safeRequest.responseLevel());
        return ResponseEntity.ok(response);
    }

    /**
     * Ask the assistant a direct question without applying a prompt template.
     *
     * @param request payload containing the conversation ID and the question
     * @return response generated by the LLM along with any sources
     */
    @PostMapping(value = "/question/simple", consumes = MediaType.APPLICATION_JSON_VALUE)
    @Operation(
            summary = "Ask a simple question without a template",
            description = "Executes a direct request to the assistant without a prompt template.")
    @ApiResponses({
        @ApiResponse(
                responseCode = "200",
                description = "Response generated successfully",
                content =
                        @Content(
                                mediaType = MediaType.APPLICATION_JSON_VALUE,
                                schema = @Schema(implementation = LlmResponseDto.class))),
        @ApiResponse(responseCode = "400", description = "Invalid request or missing parameters", content = @Content),
        @ApiResponse(
                responseCode = "500",
                description = "Internal error while calling the AI service",
                content = @Content)
    })
    public ResponseEntity<LlmResponseDto> askWithoutPromptTemplate(@Valid @NotNull @RequestBody PromptDto request) {
        PromptDto safeRequest = Objects.requireNonNull(request, "request must not be null");
        log.debug("Processing a simple question (conversationId={})", safeRequest.conversationId());

        LlmResponseDto response =
                assistantService.askWithoutPromptTemplate(safeRequest.conversationId(), safeRequest.question());
        return ResponseEntity.ok(response);
    }
}
